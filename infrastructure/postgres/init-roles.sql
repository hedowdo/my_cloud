\set ON_ERROR_STOP on
\getenv migration_password MIGRATION_PASSWORD
\getenv app_password APP_DATABASE_PASSWORD
SELECT format('CREATE ROLE cloud_migrator LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD %L', :'migration_password') \gexec
SELECT format('CREATE ROLE cloud_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD %L', :'app_password') \gexec
REVOKE ALL ON DATABASE cloud FROM PUBLIC;
GRANT CONNECT ON DATABASE cloud TO cloud_migrator, cloud_app;
ALTER SCHEMA public OWNER TO cloud_migrator;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO cloud_app;
ALTER DEFAULT PRIVILEGES FOR ROLE cloud_migrator IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO cloud_app;
ALTER DEFAULT PRIVILEGES FOR ROLE cloud_migrator IN SCHEMA public
    GRANT USAGE, SELECT ON SEQUENCES TO cloud_app;
